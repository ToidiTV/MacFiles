#!/usr/bin/env python3
"""Keep empty-results feedback aligned with native settings section filters."""
import json
import re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
keys = set()
for name in ['InfoPane.swift', 'AdditionalSettings.swift']:
    source = (root / 'Sources/FilesApp/Views' / name).read_text()
    for match in re.finditer(r'if matches\((\[[^\]]*\])\)', source):
        keys.update(json.loads(match.group(1)))
text = '''// Generated by Tools/generate-settings-index.py.
import FilesShared

enum SettingsSearchIndex {
    static let keys: [String] = %s
    static func hasMatch(_ search: String) -> Bool { search.isEmpty || keys.contains { L10n.text($0).localizedStandardContains(search) } }
}
''' % json.dumps(sorted(keys), ensure_ascii=False, indent=4)
(root / 'Sources/FilesApp/Views/SettingsSearchIndex.swift').write_bytes(text.replace('\n','\r\n').encode())
